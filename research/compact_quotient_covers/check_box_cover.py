def arc(points,r):
    """Smallest circular arc, (first residue, inclusive displacement width)."""
    a=sorted(set(int(x)%r for x in points)); assert a
    gaps=[(a[(i+1)%len(a)]-x)%r for i,x in enumerate(a)] if len(a)>1 else [r]
    i=max(range(len(a)),key=lambda j:gaps[j]);return a[(i+1)%len(a)],r-gaps[i]


def split_arc(a,r):
    x,w=a; x%=r
    if w>=r-1:return [(0,r-1)]
    if x+w<r:return [(x,x+w)]
    return [(x,r-1),(0,x+w-r)]


def add_arc(a,b,r):return ((a[0]+b[0])%r,min(r-1,a[1]+b[1]))


def merge(intervals):
    out=[]
    for a,b in sorted(intervals):
        if out and a<=out[-1][1]+1:out[-1]=(out[-1][0],max(b,out[-1][1]))
        else:out.append((a,b))
    return out


def contains_arc(a,z,r):return (z-a[0])%r<=a[1]


def gap_1d(arcs,r):
    x=0
    for a,b in merge([s for A in arcs for s in split_arc(A,r)]):
        if x<a:return x
        x=max(x,b+1)
    return x if x<r else None


def greedy_arcs(points,H,r):
    p=sorted(set(int(x)%r for x in points)); out=[]; j=0
    while j<len(p):
        a=p[j];end=min(a+H,r-1);out.append((a,end-a))
        while j<len(p) and p[j]<=end:j+=1
    assert all(any(contains_arc(A,x,r) for A in out) for x in p)
    return out


def gap_2d(boxes,r):
    """Exact rectangle-union complement by endpoint sweep; no r-by-r scan."""
    rect=[(a,b,c,d) for X,Y in boxes for a,b in split_arc(X,r) for c,d in split_arc(Y,r)]
    xs=sorted({0,r,*[v for a,b,c,d in rect for v in (a,b+1)]})
    for x in xs[:-1]:
        y=gap_1d([(c,d-c) for a,b,c,d in rect if a<=x<=b],r)
        if y is not None:return (x,y)
    return None


def add_boxes(A,B,r,k):return tuple(add_arc(A[i],B[i],r) for i in range(k))


def cover_sum(covers,r,cap):
    if prod(len(C) for C in covers)>cap:return None
    k=len(covers[0][0]); S=[((0,0),)*k]
    for C in covers:S=list(set(add_boxes(x,y,r,k) for x in S for y in C))
    return S


def line_covers(points,r,J):
    """All inclusion-minimal horizontal/vertical covers of size <=J,
    generated by branching at the first uncovered point. Each chosen line
    is replaced by its shortest cyclic arc through all points on that line.
    """
    pts=sorted(set(points)); out=set()
    def rec(left,lines):
        if not left:
            boxes=[]
            for k,c in lines:
                A=arc([x[1-k] for x in pts if x[k]==c],r)
                boxes.append(((c,0),A) if k==0 else (A,(c,0)))
            out.add(tuple(sorted(boxes)));return
        if len(lines)==J:return
        x=left[0]
        for k in (0,1):
            c=x[k];rec([y for y in left if y[k]!=c],lines+[(k,c)])
    rec(pts,[])
    return sorted(out,key=lambda x:(len(x),x))


def greedy_lines(points,r,J):
    from collections import Counter
    left=set(points);boxes=[]
    while left and len(boxes)<J:
        counts=Counter((k,x[k]) for x in left for k in (0,1))
        k,c=min(counts,key=lambda q:(-counts[q],q))
        selected={x for x in left if x[k]==c}
        A=arc([x[1-k] for x in selected],r)
        boxes.append(((c,0),A) if k==0 else (A,(c,0)));left-=selected
    return tuple(boxes) if not left else None


def det(a,b,r):return (a[0]*b[1]-a[1]*b[0])%r


def inv_coords(a,b,z,r):
    d=pow(det(a,b,r),-1,r)
    return det(z,b,r)*d%r,det(a,z,r)*d%r


def rref(rows,r,n):
    piv={};chosen=[]
    for i,row in enumerate(rows):
        x=np.array(row,dtype=np.int64)%r
        for j in sorted(piv):
            if x[j]:x=(x-int(x[j])*piv[j])%r
        nz=np.flatnonzero(x)
        if len(nz):
            j=int(nz[0]);piv[j]=x*pow(int(x[j]),-1,r)%r;chosen.append(i)
    return piv,chosen


def kernel(rows,r,n):
    piv,_=rref(rows,r,n);out=[]
    for f in sorted(set(range(n))-set(piv)):
        x=np.zeros(n,dtype=np.int64);x[f]=1
        for j in sorted(piv,reverse=True):x[j]=-int(piv[j][j+1:]@x[j+1:])%r
        out.append([int(v) for v in x])
    return out


def dot(x,y,r):return sum(int(a)*int(b) for a,b in zip(x,y))%r


