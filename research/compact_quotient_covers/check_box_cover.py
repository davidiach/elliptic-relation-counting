def coset_cover(P,l,r,h,cap):
    # Work with quotient by a line, retaining one representative for each coset.
    Q=kernel([l],r,h);assert len(Q)==h-1
    states={(0,)*(h-1):(0,)*h}
    for F in P:
        C={project(Q,a,r):a for a in F}
        nxt={}
        for p,a in states.items():
            for q,b in C.items():
                s=tuple((x+y)%r for x,y in zip(p,q))
                if s not in nxt:
                    nxt[s]=tuple((x+y)%r for x,y in zip(a,b))
                    if len(nxt)>cap:return None
        states=nxt
    return list(states.values())


def multi_flat_case(r,d,base):
    m=2;h=d+1;assert base**m>r
    F=[];labels=[]
    # A complete mixed-radix group dictionary, plus a small palette of offsets.
    for i in range(m):
        core=[j*base**i%r for j in range(base)]
        t=core+[x for x in range(1,r) if x not in core][:d]
        R=next(x for x in range(1,r) if all((x+y)%r for y in t))
        F.append([(R+x)%r for x in t]);P=[]
        for j,x in enumerate(t):
            a=[x,x]+[0]*(d-1)
            if j>=base:a[1+j-base]=(a[1+j-base]+1)%r
            P.append(tuple(a))
        labels.append(P)
    cols=[z for P in labels for z in P[1:]];n=len(cols);Z=[list(a) for a in zip(*cols)]
    assert len(rref(Z,r,n)[0])==h
    lam=Z[0];U=kernel(Z,r,n);anchor=solve_linear(Z,[1]+[0]*d,r,n)
    W=U+[anchor];rhs=[0]*len(U)+[1]
    assert len(rref(W,r,n)[0])==n-d
    # The initial explicit equations are consistent and verified by the group
    # map; they are not asserted to be a fixed-shift sparse basis.
    assert all(dot(x,lam,r)==b for x,b in zip(W,rhs))
    V=kernel(U,r,n);assert len(V)==h
    P=[];j=0
    for Fi in F:
        P.append([(0,)*h]+[tuple(V[k][a] for k in range(h)) for a in range(j,j+len(Fi)-1)])
        j+=len(Fi)-1
    # Initial homogeneous quotient support is already >=r, since the core
    # digit labels span every value in the first residual coordinate.
