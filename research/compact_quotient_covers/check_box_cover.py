def digital_fixture(r,m,base):
    assert base**m>r and 2*base<r
    # Two equal-length digit types; within-block labels must be distinct.
    forbidden={j*base**i%r for i in range(m) for j in range(-(base-1),base)}
    zeta=next(x for x in range(1,r) if x not in forbidden)
    pairs=[[(0,j*base**i%r) for j in range(base)]+[(j*base**i%r,(j*base**i+zeta)%r) for j in range(base)] for i in range(m)]
    bad={-t%r for F in pairs for c,t in F};R=next(x for x in range(1,r) if x not in bad)
    B=[[( (R+t)%r,c,t) for c,t in F] for F in pairs]
    assert all(len(set(a for a,c,t in F))==2*base and all(a for a,c,t in F) for F in B)
    n=m*(2*base-1);u=[c for F in B for a,c,t in F[1:]];lam=[t for F in B for a,c,t in F[1:]]
    rows=[];rhs=[];Z=(0,)*(2*m)
    def change(X,updates):
        Y=list(X)
        for i,j,k in updates:Y[2*i+j]=k
        return tuple(Y)
    def inc(X):
        a=[0]*n
        for i,j in enumerate(X):
            if j:a[(i//2)*(2*base-1)+j-1]+=1
        return a
    def val(X):return tuple(sum(B[i//2][j][k] for i,j in enumerate(X))%r for k in range(3))
    def add(X,Y,s):
        x,c,t=val(X);y,d,v=val(Y);assert (y-x)%r==s%r and d==c
        a=[y-x for x,y in zip(inc(X),inc(Y))];assert dot(a,u,r)==0 and dot(a,lam,r)==s%r
        rows.append(a);rhs.append(s)
    def cmp(X,Y):add(X,Y,0)
    def digs(a):
        d=[]
        for _ in range(m):a,j=divmod(a,base);d.append(j)
        assert a==0;return d
    def dtup(a):return change(Z,[(i,0,j) for i,j in enumerate(digs(a))])
    def ctup(a):return change(Z,[(i,0,base+j) for i,j in enumerate(digs(a))])
    # Calibration plus genuine zero-value contrasts; not a fixed-P-only basis.
    add(Z,change(Z,[(0,0,1)]),1)
    for i in range(m):
        cmp(change(Z,[(i,0,base)]),dtup(zeta))
        for j in range(2,base):
            cmp(change(Z,[(i,0,j)]),change(Z,[(i,0,j-1),(i,1,1)]))
            cmp(change(Z,[(i,0,base+j),(i,1,base)]),change(Z,[(i,0,base+j-1),(i,1,base+1)]))
        if i:
            cmp(change(Z,[(i-1,0,base-1),(i-1,1,1)]),change(Z,[(i,0,1)]))
            cmp(change(Z,[(i-1,0,2*base-1),(i-1,1,base+1),(i,0,base)]),change(Z,[(i-1,0,base),(i-1,1,base),(i,0,base+1)]))
    cmp(ctup(0),ctup(r))
    assert len(rref(rows,r,n)[0])==n-1 and len(rref(rows,1000003,n)[0])==n
    if n<120:
        import sympy as sp
        from sympy.matrices.normalforms import smith_normal_form
        S=smith_normal_form(sp.Matrix(rows),domain=sp.ZZ)
        assert [abs(int(S[i,i])) for i in range(n)]==[1]*(n-1)+[r]
    # Check the exact representation formula, independently against convolution.
    from math import comb
    W=(2*base)**m; M=base**m
    def conv(slots):
        a=np.zeros(r,dtype=np.int64);a[0]=1
        for F in slots:
            v=np.zeros_like(a)
            for x in F:v+=np.roll(a,x)
            a=v
        return a
    F=[[a for a,c,t in S] for S in B];counts=conv(F)
    formula=[]
    for g in range(r):
        d=0
        for k in range(m+1):
            a=(g-m*R-k*zeta)%r
            d+=comb(m,k)*(1+(M-1-a)//r)
        formula.append(d)
    assert list(counts)==formula and min(formula)>0 and sum(formula)==W
    assert all(abs(d*r-W)<=2**m*r for d in formula)
    pins=[conv([[-a%r for a in S] for S in F]+[S for j,S in enumerate(F) if j!=i]) for i in range(m)]
    lo=min(int(x.min()) for x in pins);hi=max(int(x.max()) for x in pins)
    print(f'Digital r={r}, m={m}, base={base}: {len(rows)} genuine rows, count formula exact; short fibers {min(formula)}..{max(formula)}, pins {lo}..{hi}, no-wrap {0<lo<=hi<r}.')
    return complete_joint(r,m,B,rows,rhs,lam,f'Digital completion r={r}, m={m}',2,False,r<=1009)


def solve_linear(A,b,r,n):
    rows=[list(row)+[v] for row,v in zip(A,b)];piv={}
    for row in rows:
        a=[int(x)%r for x in row]
        for j in sorted(piv):
            if a[j]:a=[(x-a[j]*y)%r for x,y in zip(a,piv[j])]
        j=next((j for j in range(n) if a[j]),None)
        if j is None:assert not a[-1];continue
        q=pow(a[j],-1,r);piv[j]=[x*q%r for x in a]
    out=[0]*n
    for j in sorted(piv,reverse=True):out[j]=(piv[j][-1]-sum(piv[j][k]*out[k] for k in range(j+1,n)))%r
    assert all(dot(a,out,r)==v%r for a,v in zip(A,b))
    return out


def project(V,x,r):return tuple(dot(a,x,r) for a in V)


def affine_gap(flats,r,h):
    """Avoid a union of fewer than r proper affine flats by greedy coordinates.
    Each flat is given by (origin, direction-generators). No field enumeration.
    """
    assert len(flats)<r
    by=[[] for _ in range(h)]
    for a,gens in flats:
        K=kernel(gens,r,h);assert K
        f=K[0];j=max(i for i,x in enumerate(f) if x)
        by[j].append((f,dot(f,a,r)))
    z=[0]*h
    for j in range(h):
        bad={(b-sum(f[i]*z[i] for i in range(j)))*pow(f[j],-1,r)%r for f,b in by[j]}
        z[j]=next(a for a in range(len(bad)+1) if a not in bad)
    for a,gens in flats:
        assert len(rref(gens+[[(x-y)%r for x,y in zip(z,a)]],r,h)[0])>len(rref(gens,r,h)[0])
    return z


