def complete_joint(r,m,B,rows,rhs,lam,label,J,greedy=False,exhaustive=True):
    n=len(lam);rank,ids=rref(rows,r,n);assert len(rank)==n-1
    # Select a genuine square rational basis, certified at an auxiliary prime.
    W=[rows[i] for i in ids];R=[rhs[i] for i in ids];p=1000003
    assert len(rref(W,p,n)[0])==n-1
    for i,a in enumerate(rows):
        if i not in ids and len(rref(W+[a],p,n)[0])==n:
            W.append(a);R.append(rhs[i]);break
    assert len(W)==n and len(rref(W,r,n)[0])==n-1
    assert all(dot(a,lam,r)==b%r for a,b in zip(W,R))
    j=next(j for j,c in enumerate(R) if c%r)
    anchor=[a*pow(R[j]%r,-1,r)%r for a in W[j]]
    U=[[(x-c*y)%r for x,y in zip(a,anchor)] for a,c in zip(W,R)]
    V=kernel(U,r,n);assert len(V)==2
    P=[];j=0
    for F in B:
        P.append([(0,0)]+[(V[0][i],V[1][i]) for i in range(j,j+len(F)-1)])
        j+=len(F)-1
    # Independent public difference directions from adjacent native addresses.
    # The full algorithm may try all pairs; this finite fast path uses only the
    # first block's adjacent differences. Nothing uses the hidden scalar table
    # or dictionary labels to form these projected coordinates.
    dirs=[]
    for x,y in zip(P[0],P[0][1:]):
        a=((y[0]-x[0])%r,(y[1]-x[1])%r)
        if a!=(0,0) and a not in dirs:dirs.append(a)
    success=None;tested=0
    for a,b in combinations(dirs,2):
        if det(a,b,r)==0:continue
        tested+=1
        labels=[[inv_coords(a,b,p,r) for p in Q] for Q in P]
        # For augmented fixtures use a bounded greedy fast path instead of
        # enumerating all exponentially many line covers. The full criterion
        # allows the branching search at the charged cap.
        lists=[]
        for Q in labels:
            C=greedy_lines(Q,r,J)
            lists.append(([C] if C is not None else []) if greedy else line_covers(Q,r,J))
        if any(not L for L in lists):continue
        # Try all small line covers up to the cap; prioritize small box counts.
        # Most finite fixtures need just the first candidate per block.
        for covers in product(*(L[:20] for L in lists)):
            S=cover_sum(covers,r,50000)
            if S is None:continue
            z=gap_2d(S,r)
            if z is not None:
                success=(a,b,labels,covers,S,z);break
        if success:break
    if not success:
        print(f'{label}: capped line-cover test failed; no rank claim.')
        return False
    a,b,labels,covers,S,z=success
    # Independently enumerate the complete *short* support for the toy fixture.
    points=set()
    for X in product(*(range(len(F)) for F in B)):
        q=tuple(sum(labels[i][x][j] for i,x in enumerate(X))%r for j in range(2));points.add(q)
    assert z not in points
    # Every nonzero scalar direction is surjective, checked exhaustively up to
    # projective scaling (r+1 directions). This is independent of the proof.
    if exhaustive:
        for k in range(r):assert len({(x+k*y)%r for x,y in points})==r
        assert len({y for x,y in points})==r
    else:
        # The two full affine axis lines already imply surjectivity in every
        # nonzero direction. This avoids an unnecessary r-times scan.
        from collections import Counter
        assert max(Counter(x for x,y in points).values())==r
        assert max(Counter(y for x,y in points).values())==r
    # Lift z using two explicit projected columns in the original coordinates.
    raw=((a[0]*z[0]+b[0]*z[1])%r,(a[1]*z[0]+b[1]*z[1])%r)
    col=[(V[0][i],V[1][i]) for i in range(n)]
    i,j=next((i,j) for i in range(n) for j in range(i+1,n) if det(col[i],col[j],r))
    A0,B0=inv_coords(col[i],col[j],raw,r);x=[0]*n;x[i]=A0;x[j]=B0
    assert (dot(x,V[0],r),dot(x,V[1],r))==raw
    # Ordinary short decomposition at the specified group point. Brute-force
    # enumeration is only for this finite ground-truth oracle.
    g0=sum(F[0][0] for F in B)%r;target=(g0+dot(x,lam,r))%r
    T=next(T for T in product(*(range(len(F)) for F in B)) if sum(B[i][j][0] for i,j in enumerate(T))%r==target)
    c=[]
    for i,F in enumerate(B):c.extend(int(T[i]==j) for j in range(1,len(F)))
    v=[(a-b)%r for a,b in zip(x,c)]
    assert dot(v,lam,r)==0 and len(rref(W+[v],r,n)[0])==n
    print(f'{label}: {n-1}/{n} -> {n}/{n}; {len(points)} distinct projected short tuples; all {r+1} scalar directions surjective; {list(map(len,covers))} per-block boxes, {len(S)} joint boxes, {tested} bases tested, one verified new row.')
    return True


def joint_case(mod,r,m,extra,seed):
    D,zeta,tau,B=mod.dictionary(r,m,extra,seed)
    rows,u,lam,_,_=mod.selected_rows(r,m,D,zeta,tau,B)
